import assert from 'node:assert/strict';
import * as THREE from 'three';
import {createStalker} from '../laboratorio/stalker.mjs';
import {createCinematicDirector,SHOTS} from '../laboratorio/cinematics.mjs';

const scene=new THREE.Scene();
const stalker=createStalker(scene);
const camera=new THREE.PerspectiveCamera(76,1.75,.035,125);
camera.position.set(0,1.6,-35);
const director=createCinematicDirector(camera,stalker);
for(const kind of ['power','exit','reveal','capture'])assert(SHOTS[kind].seconds>=1.1);
assert(director.begin('power',0));
assert(!director.begin('exit',0),'A second cutscene must not interrupt an active shot');
let shot=director.update(1);
assert.equal(shot.kind,'power');
assert.equal(shot.finished,false);
assert(camera.position.x>7&&camera.position.x<9,'Camera must film the actual security shutter');
shot=director.update(3);
assert(shot.finished&&!director.active);
assert(Math.abs(camera.position.x)<.001,'After gate shot, gameplay camera must return');

stalker.update(1/60,{x:-6,z:-35},false,12,{flashOn:true});
assert(director.begin('reveal',4));
shot=director.update(4.6);
assert(shot.progress>.1);
shot=director.update(6);
assert(shot.finished);
assert(director.begin('exit',7));
shot=director.update(8);
assert(camera.position.x>15&&camera.position.x<18,'Exit scene must film real exit');
shot=director.update(10);
assert(shot.finished);
assert(director.begin('capture',11));
shot=director.update(12.5);
assert(camera.fov>78,'Capture must animate first-person camera zoom');
assert(stalker.group.visible,'Capture must show the monster');
const jaw=stalker.group.children.find(x=>x.name==='dark open mouth');
assert(jaw&&jaw.scale.y>1,'Capture must animate the creature mouth');
shot=director.update(14);
assert(shot.finished&&!director.active);
console.log('PASS: physical shutter, revealed threat, final exit and first-person grab-to-mouth capture shots');
