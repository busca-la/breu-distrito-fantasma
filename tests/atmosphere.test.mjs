import assert from 'node:assert/strict';
import * as THREE from 'three';
import {LED_SITES,SMOKE_ZONES,REPAIR_LAMP,faultIntensity,repairPhase,eligibleForRepair,createAtmosphere} from '../laboratorio/atmosphere.mjs';
import {BRIGHTNESS_PRESETS} from '../laboratorio/visibility.mjs';
import {createCinematicDirector,SHOTS} from '../laboratorio/cinematics.mjs';
import {createStalker} from '../laboratorio/stalker.mjs';
import {circleFits} from '../laboratorio/layout.mjs';

assert(LED_SITES.length>=12,'The corridor and shops need many independent LED strips');
assert(SMOKE_ZONES.length>=5,'Smoke should be local to several physically authored faults');
assert(faultIntensity(12.3,0)<.08,'Worn ballast must actually brown out');
assert(faultIntensity(2,0)>.75,'Normal circuit should not strobe constantly');
assert.equal(repairPhase(.30),'reach');
assert.equal(repairPhase(.65),'impact');
assert.equal(repairPhase(.94),'stable');
const player={x:0,z:-17.3};
assert(circleFits(player.x,player.z,.33),'Automatic repair must be reachable without walking through a wall');
assert(!eligibleForRepair(player,{time:0,started:false,done:false}),'No repair before gameplay');
assert(eligibleForRepair(player,{time:12,started:false,done:false}),'Repair should happen automatically for a nearby player');
assert(!eligibleForRepair(player,{time:12,started:false,done:true}),'Repair must happen only once');

const scene=new THREE.Scene(),world=createAtmosphere(scene,{lowPower:true});
assert.equal(world.leds.length,12);
assert(scene.children.some(x=>x.name==='Subtle wet floor patches'&&x.isInstancedMesh),'No realistic wet reflecting floor details');
assert(world.repair.children.some(x=>x.name==='Loose ceiling electrical cable'),'Repair fixture lacks an actual visible cable');
assert.equal(world.tinyLights.length,3,'No expensive forest of real shadow lights');
assert.equal(world.clouds.length,5);
assert(world.clouds.every(c=>c.seeds.length<=12),'Low power device gets bounded smoke particles');
assert(world.clouds.every(c=>c.material.depthWrite===false),'Smoke must not form solid invisible walls');
world.update(9,player);
assert(world.clouds.some(c=>c.plume.visible),'Nearby smoke must actually render');
assert(world.clouds.some(c=>!c.plume.visible),'Distant smoke should be culled');
assert(world.beginRepair(20));
assert(!world.beginRepair(20.3),'Automatic action cannot restart while running');
world.update(21.1,player);
assert(!world.repaired,'Lamp cannot restart before the hit');
const events=world.update(22.5,player);
assert(world.repaired,'Lamp must physically restart during impact');
assert(events.some(e=>e.kind==='lamp-hit'),'Impact should emit synchronized audio cue');
assert(world.inspectionLight.intensity>0,'Restored lamp needs real local light');
world.update(23.6,player);
assert(!world.repairing,'The action must end automatically');
assert(!world.eligible(player,50),'Do not repeat the repair on revisits');

const camera=new THREE.PerspectiveCamera(76,1.75,.05,125);
camera.position.set(player.x,1.65,player.z+1);
const stalker=createStalker(scene),director=createCinematicDirector(camera,stalker,world);
assert(SHOTS.repair.seconds>=3);
assert(SHOTS.repair.beats.length>=3);
assert(director.begin('repair',25));
let shot=director.update(26.6);
assert(shot.kind==='repair'&&director.arm.visible,'The player hand must visibly reach for the fixture');
assert(shot.progress>.2&&shot.progress<1);
shot=director.update(29);
assert(shot.finished&&!director.active&&!director.arm.visible,'Return to player after automatic shot');
assert(Math.abs(camera.position.x-player.x)<.01,'Camera must restore the original position');
assert(BRIGHTNESS_PRESETS.every(x=>x.ambient<.3),'Peripheral darkness must remain dominant');
console.log('PASS: 12 independent LEDs, wet surfaces, local 5-zone smoke, timed failures and automatic physical first-person lamp repair');
