import assert from 'node:assert/strict';
import * as THREE from 'three';
import {LED_SITES,SMOKE_ZONES,faultIntensity,createAtmosphere} from '../laboratorio/atmosphere.mjs';
import {FLASHLIGHT_STATES,FlashlightFaultMachine,createFlashlightRig} from '../laboratorio/flashlight-rig.mjs';
import {BRIGHTNESS_PRESETS} from '../laboratorio/visibility.mjs';

assert(LED_SITES.length>=12);
assert(SMOKE_ZONES.length>=5);
assert(faultIntensity(12.3,0)<.08);
assert(faultIntensity(2,0)>.75);
const scene=new THREE.Scene(),player={x:0,z:-17.3};
const world=createAtmosphere(scene,{lowPower:true});
assert(!scene.children.some(x=>x.name?.includes('automatic tap')),'Ceiling-lamp repair scene must be removed');
assert.equal(world.tinyLights.length,3);
assert.equal(world.clouds.length,5);
assert(world.clouds.every(c=>c.seeds.length<=12));
assert(world.clouds.every(c=>c.material.depthWrite===false));
world.update(9,player);
assert(world.clouds.some(c=>c.plume.visible));
assert(world.clouds.some(c=>!c.plume.visible));

const camera=new THREE.PerspectiveCamera(76,1.75,.05,125);
const rig=createFlashlightRig(camera,{firstFault:6,interval:30});
assert(camera.children.includes(rig.rig));
assert(rig.rig.getObjectByName('Hand holding own flashlight'));
assert(rig.rig.getObjectByName('Automatic striking hand'));
const machine=new FlashlightFaultMachine({firstFault:6,interval:30});
assert.deepEqual(FLASHLIGHT_STATES,['normal','interference','blinking','failure','repair','recovery']);
assert.equal(machine.update(5).state,'normal');
assert.equal(machine.update(6).state,'interference');
assert.equal(machine.update(7.9).state,'blinking');
assert.equal(machine.update(10.1).state,'failure');
assert.equal(machine.update(11.3).state,'repair');
assert(machine.update(12.1).events.includes('flashlight-hit'));
assert(machine.update(12.6).events.includes('flashlight-hit'));
assert.equal(machine.update(13.1).state,'recovery');
machine.setManual(false);
assert.equal(machine.update(14).output,0);
assert.equal(machine.update(14.7).state,'normal');
assert.equal(machine.update(14.7).output,0,'Automatic repair must not relight a manually disabled lamp');
assert(BRIGHTNESS_PRESETS.every(x=>x.ambient<.3));
console.log('PASS: LEDs, smoke and held flashlight state machine with two automatic physical strikes');
